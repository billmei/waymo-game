#!/usr/bin/env python3
"""Build js/isle.js: Slop Skies' own island generator and its renderer, lifted out of the shipped
engine bundle (reference/slop-skies/dr.js) so Waymo Care stands on exactly the same toy San Francisco.

It takes, verbatim, the bundle's src/core.js (geometry helpers, the baked light), src/data.js (the
neighbourhood map), src/island.js (terrain, city blocks, terraces, towers, landmarks, trees, roads,
boats) and src/render.js (the shared uniforms, the world shader, sky, sea, clouds and blob shadows),
wraps them in one closure and exposes a small API as WG.isle. Run it again after replacing dr.js.

    python3 tools/extract_isle.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
src = (ROOT / "reference/slop-skies/dr.js").read_text().split("\n")


def section(name):
    """Lines of one src/ module, from its marker to the next one."""
    start = next(i for i, l in enumerate(src) if l.strip() == "/* ---- src/%s ---- */" % name)
    end = next(i for i in range(start + 1, len(src)) if src[i].lstrip().startswith("/* ---- src/"))
    return src[start:end]


def cut_from(lines, pattern):
    """Drop everything from the first line matching pattern (the engine's hooks at a module's end)."""
    for i, l in enumerate(lines):
        if re.search(pattern, l):
            return lines[:i]
    raise SystemExit("pattern not found: " + pattern)


core = section("core.js")
data = section("data.js")
island = cut_from(section("island.js"), r"^\s*window\.__island = \{")
render = section("render.js")
for mod in (core, data, island, render):
    for l in mod:
        if re.search(r"\bawait\b|\bDRX\b", l):
            raise SystemExit("engine hook left in extracted code: " + l.strip())

head = '''/* Waymo Care · the island. GENERATED by tools/extract_isle.py from reference/slop-skies/dr.js: Slop Skies' own
   src/core.js, src/data.js, src/island.js and src/render.js, verbatim, so the game stands on the very same toy
   San Francisco (terrain, neighbourhoods, terraces, towers, landmarks, trees, sea, sky). Do not edit by hand. */
(function () {
  "use strict";
  if (typeof THREE === "undefined") throw new Error("load three.js r128 before isle.js");
'''
tail = '''
  /* ---------- the API Waymo Care uses ---------- */
  // boot in Slop Skies' order (engine/game.js): textures, sky, the island, then the sea, shadows and clouds.
  // S enlarges the island for play at street level (Slop Skies squeezes San Francisco for flying over it): everything
  // but the sky, which follows the camera, goes in one group scaled by S, and the few shader terms that are in absolute
  // metres (the coastline field's box, the haze's height scale, the landmark marks) are scaled to match
  let SKYO = null,
    GROUP = null;
  function boot(scn, glRenderer, S) {
    if (SKYO) return SKYO;
    S = S || 1;
    renderer = glRenderer;
    lookTextures();
    initShared(scn);
    SKYO = addSky(scn);
    GROUP = new T.Group();
    GROUP.name = "island";
    GROUP.scale.setScalar(S);
    scn.add(GROUP);
    buildWorldMeshes(GROUP);
    buildClouds(GROUP);
    GROUP.updateMatrixWorld(true);
    const b = U.uShoreBox.value;
    b.set(b.x * S, b.y * S, b.z / S, b.w / S);
    U.uFogH.value *= S;
    const om = ISLAND.meshes.objects && ISLAND.meshes.objects.material;
    if (om && om.uniforms.uMarks && Array.isArray(om.uniforms.uMarks.value))
      for (const v of om.uniforms.uMarks.value) v.multiplyScalar(S);
    return SKYO;
  }
  // what Slop Skies' drawScene does before each render
  function frame(camera, dt, vw, vh) {
    camera.updateMatrixWorld();
    if (SKYO) syncSky(SKYO, camera);
    U.uCam.value.copy(camera.position);
    U.uTime.value += dt;
    U.uVP.value.set(0, 0, 1 / Math.max(1, vw), 1 / Math.max(1, vh));
    syncMats();
    updClouds(camera);
  }
  window.WG = window.WG || {};
  window.WG.isle = {
    T,
    U,
    ISL,
    ISLAND,
    ISLE,
    MARKS,
    DECKS,
    LIGHT,
    SUN,
    hex,
    mat,
    Geo,
    setLook,
    setGrade,
    LOOK_GRADES,
    boot,
    frame,
    blobShadows,
    groundH,
    hitsBuilding,
    hitsDeck,
    idAt,
    zoneName,
    get MATS() {
      return MATS;
    },
  };
})();
'''
out = head + "\n".join(core + data + island + render) + tail
(ROOT / "js/isle.js").write_text(out)
print("js/isle.js: %d lines, %d KB" % (out.count("\n"), len(out) // 1024))
